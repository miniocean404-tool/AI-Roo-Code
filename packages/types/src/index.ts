/**
 * @fileoverview Roo Code 类型定义包的主入口文件
 *
 * 这个包包含了 Roo Code 项目中所有共享的 TypeScript 类型定义。
 * 它被多个包使用，包括：
 * - src/ (VS Code 扩展主代码)
 * - webview-ui/ (React 前端)
 * - apps/cli/ (命令行工具)
 * - packages/cloud/ (云服务)
 *
 * 类型定义按功能模块组织：
 *
 * 核心类型：
 * - api: RooCodeAPI 接口定义，用于扩展与外部交互
 * - task: 任务相关类型（TaskLike, TaskStatus 等）
 * - message: 消息类型（ClineMessage, ClineAsk, ClineSay 等）
 * - tool: 工具相关类型（ToolName, ToolGroup 等）
 * - mode: 模式配置类型（ModeConfig, DEFAULT_MODES 等）
 *
 * 提供者相关：
 * - provider-settings: API 提供者配置（ProviderSettings, ProviderName 等）
 * - model: 模型信息类型（ModelInfo, ReasoningEffort 等）
 * - providers/: 各个 AI 提供者的模型定义
 *
 * 功能模块：
 * - cloud: 云服务相关类型
 * - mcp: Model Context Protocol 类型
 * - codebase-index: 代码库索引类型
 * - context-management: 上下文管理类型
 * - history: 历史记录类型
 * - marketplace: 市场相关类型
 *
 * 其他：
 * - events: 事件名称枚举
 * - telemetry: 遥测数据类型
 * - ipc: 进程间通信类型
 * - vscode: VS Code 相关类型
 */

